/* =========================================================
   LANGUAGE HELPER
========================================================= */

function getTranslation(key, language = "en") {

    if (
        interfaceTranslations[language] &&
        interfaceTranslations[language][key]
    ) {

        return interfaceTranslations[language][key];

    }


    /* English fallback */

    if (
        interfaceTranslations.en &&
        interfaceTranslations.en[key]
    ) {

        return interfaceTranslations.en[key];

    }


    return key;

}


/* =========================================================
   EXPORT
========================================================= */

window.interfaceTranslations =
    interfaceTranslations;

window.getTranslation =
    getTranslation;
